#############################################################################################

sub table_of_contents {
    my @headers     = @_;
    my $last_level  = 0;
    my $out         = '';

    $out .= "        <h1>" . gettext("Contents") . "</h1>\n";
    foreach my $header ( @headers ) {
        my $level = $header->{'level'};
        if ( $level <= $last_level ) {
            $out .= "        </li>\n";
        }
        if ( $level < $last_level ) {
            while ( $level < $last_level ) {
                $out .= "        </ol>\n        </li>\n";
                $last_level--;
            }
        } else {
            while ( $level > $last_level ) {
                $out .= "        <ol>\n";
                $last_level++;
            }
        }
        $out .= sprintf( "        <li>%s <a href=\"#%s\">%s</a>\n", $header->{'number'}, $header->{'id'}, wiki2html( rt($header->{'text'}), 1 ) );
    }
    while ( $last_level > 0) {
        $out .= "        </li>\n        </ol>\n";
        $last_level--;
    }

    return $out;
}


#############################################################################################

sub render_node {
    my $node = shift;
    my $type = $node->{'type'};

    return render_paragraph( $node )            if ( $type eq 'paragraph'    );
    return render_list( $node->{'items'}, '' )  if ( $type eq 'list'         );
    return render_table( $node )                if ( $type eq 'table'        );

    return '';
}


