package PtnaOutput::Html;

#############################################################################################
#
# HTML renderer for the PTNA document model.
#
# The analysis (bin/ptna-routes.pl) does not write HTML any more, it provides the data. The data is
# grouped by what it is about; sections, their titles, order and numbers are decided by this renderer.
#
#   $doc = { 'meta'   => { 'title' => 'Page title', 'osm_base', 'areas' },
#            'routes' => [ <block>, ... ],
#            <topic> => <collection>, ... }
#
# 'routes'   what comes from the routes file, in its order. A block with the type 'header' ('level', 'text')
#            starts a new section, all the other blocks belong to the section of the preceding header.
# <topic>    a collection (one key per topic of the document): a list of tables (considerednetworks,
#            addednetworks) or { 'content' => [ <block>, ... ] } and/or { 'route_types' => { <route_type> => [ <block>, ... ] } }.
#            The topics are: unassigned, lines, lines_without_ref, life_cycle_prefix, excluded, morerelations,
#            networkdetails, considerednetworks, addednetworks, notconsiderednetworks, operatordetails,
#            gtfsreferences, gtfsreferences_csv, gtfsreferences_relations, conditional_on_ways.
#            The renderer provides the titles, the nesting and the order of the topics and of the route types.
#
# The section with the dates of the data (or the hints) which starts the page is not part of the document.
# The numbers of the sections ("2.1"), the table of contents and the local navigation (links to the
# lines of the tables of a section) are not part of the document, they are derived here. The anchor of
# a topic is its fixed name (#networkdetails), the other sections are 'A' followed by their number.
#
# The structure of the document (blocks, rows, cells, messages) is described by the JSON Schema
# doc/ptna-analysis.schema.json.
#
# The explanatory texts of the page (notes below the 'dates'/'hints' header, introductions of the
# sections, the request-analysis button) are generated by the renderer: they are selected by the topic
# of the section and are not part of the document. The dates come from meta
# 'osm_base' and 'areas'.
#
# Strings which are marked as 'rich', 'html' or 'wiki' may contain inline markup.
#
#############################################################################################

