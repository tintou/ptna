# cells without data are not part of the document
sub empty_cell {
    my $column = shift;

    return {}                   if ( $column eq 'relation' );
    return {}                   if ( $column eq 'gtfs_feed' );
    return { 'links' => [] }    if ( $column eq 'relations' || $column eq 'ways' );
    return [];
}


# the 'id' of a line is the id of its relation, only the first line of a relation gets it
sub line_id {
    my $row = shift;
    my $rel = $row->{'cells'} && $row->{'cells'}->{'relation'};

    return undef    unless ( $rel && $rel->{'id'} );

    my $id = html_escape( $rel->{'id'} );
    $id =~ s/[^0-9A-Za-z_.-]/_/g;
    return undef    if ( $used_ids{$id} );
    $used_ids{$id} = 1;
    return $id;
}


sub render_line {
    my $row     = shift;
    my @columns = @_;
    my $cells   = $row->{'cells'} || {};
    my $out     = '';

    my $id      = line_id( $row );

    $out .= sprintf( "%16s<tr %sdata-info=\"%s\" data-ref=\"%s\" class=\"line\">", ' ', (defined($id) ? sprintf( "id=\"%s\" ", $id ) : ''), html_escape($row->{'info'}), html_escape($row->{'ref'}) );
    foreach my $column ( @columns ) {
        my $cell = $cells->{$column} // empty_cell( $column );
        if ( $column eq 'relation' ) {
            $out .= sprintf( "<td class=\"relation\" dir=\"auto\">%s</td>", $cell->{'id'} ? relation_link( $cell->{'link'} ) : '' );
        } elsif ( $column eq 'relations' ) {
            $out .= sprintf( "<td class=\"relations\" dir=\"auto\">%s%s</td>", join( ', ', map { relation_link($_); } @{$cell->{'links'}} ), and_more( $cell ) );
        } elsif ( $column eq 'ways' ) {
            $out .= sprintf( "<td class=\"ways\" dir=\"auto\">%s%s</td>", join( ', ', map { way_link($_); } @{$cell->{'links'}} ), and_more( $cell ) );
        } elsif ( $column eq 'issues' || $column eq 'notes' ) {
            $out .= sprintf( "<td class=\"%s\" dir=\"auto\">%s</td>", $column, join( '<br>', map { rt($_); } @{$cell} ) );
        } elsif ( $column eq 'gtfs_feed' ) {
            $out .= sprintf( "<td class=\"%s\" dir=\"auto\">%s</td>", $column, gtfs_feed_link( $cell ) );
        } else {
            my @lines = ref($cell) eq 'ARRAY' ? @{$cell} : ( $cell );
            $out .= sprintf( "<td class=\"%s foreign\" dir=\"auto\">%s</td>", $column, join( '<br>', map { html_escape(rt($_)); } @lines ) );
        }
    }
    $out .= "</tr>\n";

    return $out;
}


