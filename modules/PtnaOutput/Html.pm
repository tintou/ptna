my %gtfs_page   = ( 'route' => 'trips.php', 'trip' => 'single-trip.php', 'shape' => 'shape.php' );
my %gtfs_class  = ( 'valid' => 'gtfs-datevalid', 'past' => 'gtfs-dateold', 'future' => 'gtfs-datenew', 'previous' => 'gtfs-dateprevious' );
my %gtfs_label  = ( 'valid' => 'GTFS', 'past' => 'GTFS?', 'future' => 'GTFS?', 'previous' => 'GTFS??' );

# text describing the status of a GTFS object, as part of the title of a link
sub gtfs_status_text {
    my $link   = shift;
    my $status = $link->{'status'};

    return $link->{'from'} . ' - ' . $link->{'to'}                                                                                  if ( $status eq 'valid' );
    return html_escape( gettext("is no longer valid (in the past)") . ': ' . $link->{'from'} . ' - ' . $link->{'to'} )             if ( $status eq 'past' );
    return html_escape( gettext("is not yet valid (in the future)") . ': ' . $link->{'from'} . ' - ' . $link->{'to'} )             if ( $status eq 'future' );
    return html_escape( gettext("is outdated, fits to older GTFS version only") )                                                   if ( $status eq 'previous' );
    return html_escape( gettext("does not provide any 'shape' data") )                                                              if ( $status eq 'no_shapes' );
    return html_escape( gettext("does not exist") );
}


sub gtfs_link {
    my $link   = shift;
    my $status = $link->{'status'};
    my $label  = $link->{'route_only'} ? 'GTFS(r)' : 'GTFS';
    my $feed   = $link->{'feed'}         // '';
    my $date   = $link->{'release_date'} // '';

    if ( $status eq 'no_feed' ) {
        return sprintf( "<a class=\"bad-link\" href=\"/gtfs/\" title=\"'GTFS feed' %s. %s\">%s!</a>",
                        html_escape(gettext("is not set")), html_escape(gettext("GTFS database not found")), $label );
    }
    if ( $status eq 'no_db' ) {
        return sprintf( "<a class=\"bad-link\" href=\"/gtfs/\" title=\"GTFS-Feed: %s, GTFS-Release-Date: %s : %s.\">%s!</a>",
                        html_escape($feed), html_escape($date), html_escape(gettext("GTFS database not found")), $label );
    }

    my $country = gtfs_uri_escape( gtfs_country($feed) );
    my $query   = sprintf( "feed=%s&release_date=%s", gtfs_uri_escape($feed), gtfs_uri_escape($date) );
    my $prefix  = sprintf( "GTFS-Feed: %s, GTFS-Release-Date: %s", html_escape($feed), html_escape($date) );

    if ( $status eq 'no_id' ) {
        return sprintf( "<a class=\"bad-link\" href=\"/gtfs/%s/routes.php?%s\" title=\"%s, '%s' %s.\">%s!</a>",
                        $country, $query, $prefix, html_escape($link->{'tag'}), html_escape(gettext("is not set")), $label );
    }

    my $what   = $link->{'what'};
    my $id     = $link->{'id'};
    my $class  = $gtfs_class{$status} // 'bad-link';
    my $text   = $gtfs_label{$status} // 'GTFS!';
    my $dot    = ( $status eq 'valid' ) ? '' : '.';
    my $lead   = ( $what eq 'trip' && $status eq 'future' ) ? ', ' : '';      # historic quirk of the output
    $text      =~ s/^GTFS/$label/;

    return sprintf( "%s<a class=\"%s\" href=\"/gtfs/%s/%s?%s&%s_id=%s\" title=\"%s, '%s' = '%s' %s%s\">%s</a>",
                    $lead, $class, $country, $gtfs_page{$what}, $query, $what, gtfs_uri_escape(encode('utf8',$id)),
                    $prefix, html_escape($link->{'tag'}), html_escape($id), gtfs_status_text($link), $dot, $text );
}


# the status of a GTFS object only, used when reporting problems
sub gtfs_status {
    my $link   = shift;
    my $status = $link->{'status'};

    return sprintf( "GTFS-Feed: %s, GTFS-Release-Date: %s : %s", $link->{'feed'} // '', $link->{'release_date'} // '', gettext("GTFS database not found") )   if ( $status eq 'no_db' );
    return sprintf( "'GTFS feed' %s. %s", gettext("is not set"), gettext("GTFS database not found") )                                                          if ( $status eq 'no_feed' );
    return sprintf( "'%s' %s", $link->{'tag'}, gettext("is not set") )                                                                                         if ( $status eq 'no_id' );
    return sprintf( "'%s' = '%s' %s", $link->{'tag'}, $link->{'id'}, gtfs_status_text($link) );
}


