# the columns which can be sorted in the browser: not for tables with groups (sub-headers)
sub table_sort {
    my $node    = shift;
    my @columns = @_;
    my %type    = ( 'ref' => 'number', 'relation' => 'number', 'number' => 'number',
                    'conditional_access' => 'string', 'key' => 'string', 'value' => 'string' );
    my %sort    = ();

    return ()    if ( grep { $_->{'type'} eq 'subheader'; } @{$node->{'rows'}} );

    $type{'gtfs_feed'} = 'string'    unless ( grep { $_ eq 'feed_from'; } @columns );
    foreach my $column ( @columns ) {
        $sort{$column} = $type{$column}    if ( $type{$column} );
    }

    return %sort;
}


sub render_table {
    my $node        = shift;
    my @columns     = @{$node->{'columns'}};
    my %sort        = table_sort( $node, @columns );
    my $prefix      = '';
    my $out         = '';

    if ( scalar(keys(%sort)) ) {
        $out   .= sprintf( "%8s<table class=\"oepnvtable js-sort-table\">\n", ' ' );
        $prefix = '&#x21C5;';
    } else {
        $out   .= sprintf( "%8s<table class=\"oepnvtable\">\n", ' ' );
    }
    $out .= sprintf( "%12s<thead>\n", ' ' );
    $out .= sprintf( "%16s<tr class=\"tableheaderrow\">", ' ' );
    foreach my $column ( @columns ) {
        if ( $sort{$column} ) {
            $out .= sprintf( "<th class=\"%s js-sort-%s\" dir=\"auto\">%s%s</th>", $column, $sort{$column}, $prefix, column_label($column) );
        } else {
            $out .= sprintf( "<th class=\"%s\" dir=\"auto\">%s%s</th>", $column, $prefix, column_label($column) );
        }
    }
    $out .= "</tr>\n";
    $out .= sprintf( "%12s</thead>\n", ' ' );
    $out .= sprintf( "%12s<tbody>\n", ' ' );

    foreach my $row ( @{$node->{'rows'}} ) {
        if ( $row->{'type'} eq 'subheader' ) {
            $out .= render_subheader( $row, scalar(@columns) );
        } else {
            $out .= render_line( $row, @columns );
        }
    }

    $out .= sprintf( "%12s</tbody>\n",  ' ' );
    $out .= sprintf( "%8s</table>\n\n", ' ' );

    return $out;
}


