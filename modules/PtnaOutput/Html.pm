# the dates, the general notes and the button to request a new analysis are part of the HTML page only,
# the dates are taken from the meta data of the document
sub render_page_notes {
    my $node  = shift;
    my $name  = $node->{'topic'} // '';
    my $out   = '';
    my @lines = ();

    return ''    unless ( $name eq 'dates' || $name eq 'hints' );

    push( @lines, sprintf( "OSM-Base Time : %s", $DOC_META->{'osm_base'} ) )    if ( $DOC_META->{'osm_base'} );
    push( @lines, '<br>' )                                                       if ( $DOC_META->{'osm_base'} && $DOC_META->{'areas'} );
    push( @lines, sprintf( "Areas Time    : %s", $DOC_META->{'areas'} ) )       if ( $DOC_META->{'areas'} );
    $out .= render_paragraph( { 'indent' => 8, 'lines' => \@lines, 'blank_after' => 1 } )    if ( $name eq 'dates' );
    $out .= render_paragraph( { 'indent' => 8, 'lines' => [ gettext("The data will be updated when the result of the analysis has changed.") ] } );
    $out .= render_paragraph( { 'indent' => 8, 'lines' => [ gettext("An explanation of the error texts can be found in the documentation at '<a href='/en/index.php#messages'>Messages</a>'.") ] } );
    $out .= render_request_analysis()    if ( !$cfg{'test'} );
    return $out;
}


#############################################################################################

sub render_header {
    my $node = shift;
    my $out  = '';

    if ( $node->{'text'} ) {
        $out .= "        <hr />\n"    if ( $node->{'level'} == 1 );
        $out .= sprintf( "        <h%d id=\"%s\">%s %s</h%d>\n", $node->{'level'}, $node->{'id'}, $node->{'number'}, wiki2html(rt($node->{'text'})), $node->{'level'} );
    }

    # local navigation: links to the lines of the table(s) following this header
    foreach my $nav ( @{$node->{'nav'} || []} ) {
        my $bg_colour         = get_colour_from_string( $nav->{'colour'} );
        my $text_colour       = $nav->{'text_colour'} // '';
        my $fg_colour         = ($text_colour ne '') ? get_colour_from_string($text_colour) : get_foreground_from_background($bg_colour);
        my $outer_span_begin  = '';
        my $inner_span_begin  = '';
        my $outer_span_end    = '';
        my $inner_span_end    = '';

        if ( $bg_colour && $fg_colour && $cfg{'coloured_sketchline'} ) {
            $outer_span_begin = sprintf( "<span style=\"background-color: %s; border-style: solid; border-color: gray; border-width: 1px;\"><nobr>&nbsp;", $bg_colour );
            $inner_span_begin = sprintf( "<span style=\"color: %s\">", $fg_colour );
            $outer_span_end   = "&nbsp;</nobr></span>";
            $inner_span_end   = "</span>";
        }
        $out .= sprintf( "%s<a href=\"#%s\">%s%s%s</a>%s ", $outer_span_begin, html_escape($nav->{'id'}), $inner_span_begin, handle_foreign(rt($nav->{'text'})), $inner_span_end, $outer_span_end );
    }
    $out .= "</br></br>\n"  if ( scalar( @{$node->{'nav'} || []} ) );

    return $out;
}


#############################################################################################

sub render_paragraph {
    my $node    = shift;
    my @lines   = @{$node->{'lines'} || []};
    my $indent  = $node->{'indent'} ? ' ' x $node->{'indent'} : '';
    my $prefix  = $node->{'indent'} ? $indent . '    ' : '';
    my $out     = '';

    if ( ($node->{'markup'} || '') eq 'wiki' ) {
        @lines = map { wiki_line( rt($_) ); } @lines;
    } else {
        @lines = map { rt($_); } @lines;
    }

    $out .= "$indent<p>\n";
    if ( scalar( @lines ) ) {
        foreach my $line ( @lines ) {
            $out .= "$prefix$line\n";
        }
        $out .= "\n"    if ( $node->{'loose'} );
    } else {
        $out .= "&nbsp;\n";
    }
    $out .= "$indent</p>\n";
    $out .= "\n"        if ( $node->{'blank_after'} );

    return $out;
}


#############################################################################################

sub wiki_line {
    my $wikitext = wiki2html( shift );

    while ( $wikitext =~ m/^\s/ ) {
        $wikitext =~ s/^(\s*)\s/$1&nbsp;/;
    }

    return $wikitext;
}


#############################################################################################

sub render_list {
    my $items   = shift;
    my $indent  = shift;
    my $out     = "$indent<ul>\n";

    foreach my $item ( @{$items} ) {
        $out .= "$indent    <li>" . rt($item->{'text'});
        if ( $item->{'children'} && scalar( @{$item->{'children'}} ) ) {
            $out .= "\n";
            $out .= render_list( $item->{'children'}, "$indent        " );
            $out .= "$indent    </li>\n";
        } else {
            $out .= "</li>\n";
        }
    }
    $out .= "$indent</ul>\n";

    return $out;
}


#############################################################################################

sub render_simple_table {
    my $node = shift;
    my $out  = '';

    $out .= "<table>\n";
    $out .= "    <thead class=\"tableheaderrow\">\n";
    $out .= "        <tr>" . join( '', map { "<th>" . rt($_) . "</th>"; } @{$node->{'header'}} ) . "</tr>\n";
    $out .= "    </thead>\n";
    $out .= "    <tbody>\n";
    foreach my $row ( @{$node->{'rows'}} ) {
        $out .= "        <tr>" . join( '', map { "<td>" . rt($_) . "</td>"; } @{$row} ) . "</tr>\n";
    }
    $out .= "    </tbody>\n";
    $out .= "</table>\n";

    return $out;
}


