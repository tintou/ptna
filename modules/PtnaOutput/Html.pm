sub render_subheader {
    my $row             = shift;
    my $no_of_columns   = shift;
    my @refs            = @{$row->{'refs'} || []};
    my $csv             = $row->{'csv'} || {};
    my $refs_text       = join( ' ', @refs );
    my $csv_text        = '';

    return ''   if ( $no_of_columns <= 1 || $refs_text eq '' );

    my $ref_text = join( ' ', map { sketchline( $_, $row->{'network'}, $row->{'operator'}, $row->{'pt_type'}, $row->{'colour'}, $row->{'text_colour'} ) } @refs );

    return ''   if ( $ref_text eq '' );

    if ( $csv->{'comment'} ) {
        $csv_text .= sprintf( "%s: <span class=\"foreign\" dir=\"auto\">%s</span>; ", column_label_or( 'CSV-Comment', 'Comment' ), wiki2html( rt($csv->{'comment'}) ) );
        $csv_text =~ s|!([^!]+)!|<span class=\"attention\">$1</span>|g;
    }
    $csv_text .= sprintf( "%s: %s; ", column_label_or( 'CSV-From',     'From'     ), handle_foreign(rt($csv->{'from'})) )       if ( $csv->{'from'}     );
    $csv_text .= sprintf( "%s: %s; ", column_label_or( 'CSV-To',       'To'       ), handle_foreign(rt($csv->{'to'})) )         if ( $csv->{'to'}       );
    $csv_text .= sprintf( "%s: %s; ", column_label_or( 'CSV-Operator', 'Operator' ), handle_foreign(rt($csv->{'operator'})) )   if ( $csv->{'operator'} );
    $csv_text .= rt($csv->{'gtfs'}) if ( $csv->{'gtfs'} );
    $csv_text =~ s/; $//;

    my $info = $csv_text ? $csv_text : '???';
       $info =~ s/\"/_/g;

    return sprintf( "%16s<tr %sdata-info=\"%s\" data-ref=\"%s\" class=\"sketchline\"><td class=\"sketch\" dir=\"auto\">%s</td><td class=\"csvinfo\" colspan=\"%d\" dir=\"auto\">%s</td></tr>\n",
                    ' ', (defined($row->{'id'}) ? sprintf( "id=\"%s\" ", $row->{'id'} ) : ''), $info, html_escape($refs_text), $ref_text, $no_of_columns-1, $csv_text );
}


