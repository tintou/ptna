sub init {
    my %opts = @_;
    foreach my $key ( keys( %cfg ) ) {
        $cfg{$key} = $opts{$key}    if ( exists( $opts{$key} ) );
    }
}


#############################################################################################

our $DOC_META = {};
my %used_ids  = ();                 # ids of the table rows already written, an id may only be used once

sub render {
    my $doc      = shift;

    $DOC_META = $doc->{'meta'} || {};
    %used_ids = ();

    my @sections = ordered_sections( $doc );
    my @headers  = grep { $_->{'text'}; } @sections;

    print start_of_page( $DOC_META );
    print table_of_contents( @headers );
    my %state = ();
    foreach my $section ( @sections ) {
        print render_header( $section ) . render_page_notes( $section );
        print render_help_after( $section, \%state );
        foreach my $block ( @{$section->{'content'} || []} ) {
            print render_help_before( $block, \%state );
            print render_node( $block );
        }
    }
    print end_of_page();
}


#############################################################################################

# builds the list of the sections of the page from the data and adds what is derived from it:
# 'number', 'id' (anchor) and 'nav' (local navigation)
my @TOPIC_ORDER   = ( 'unassigned', 'lines', 'lines_without_ref', 'life_cycle_prefix', 'excluded', 'morerelations',
                      'networkdetails', 'considerednetworks', 'addednetworks', 'notconsiderednetworks', 'operatordetails',
                      'gtfsreferences', 'gtfsreferences_csv', 'gtfsreferences_relations', 'conditional_on_ways' );
my %SUB_TOPICS    = map { $_ => 2; } ( 'considerednetworks', 'addednetworks', 'notconsiderednetworks', 'gtfsreferences_csv', 'gtfsreferences_relations' );
my @ROUTE_TYPES   = ( 'train', 'subway', 'light_rail', 'tram', 'trolleybus', 'bus', 'ferry', 'monorail', 'aerialway', 'funicular', 'share_taxi', 'coach' );

sub ordered_sections {
    my $doc      = shift;
    my @ordered  = ();
    my @counters = (0) x 7;

    # the page always starts with the dates of the data, or with the hints if there are no dates
    push( @ordered, { 'level' => 1, 'topic' => ( $DOC_META->{'osm_base'} || $DOC_META->{'areas'} ) ? 'dates' : 'hints', 'content' => [] } );

    # the routes list: the headers split it into sections, what comes before the first header has no title
    my $section = undef;
    foreach my $block ( @{$doc->{'routes'} || []} ) {
        if ( $block->{'type'} eq 'header' ) {
            $section = { 'level' => $block->{'level'}, 'text' => $block->{'text'}, 'content' => [] };
            push( @ordered, $section );
        } else {
            unless ( $section ) {
                $section = { 'level' => 1, 'content' => [] };
                push( @ordered, $section );
            }
            push( @{$section->{'content'}}, $block );
        }
    }

    foreach my $topic ( @TOPIC_ORDER ) {
        my $collection = $doc->{$topic} or next;
        my $name       = $topic;
        $name = 'other_lines'    if ( $topic eq 'lines' && scalar( @{$doc->{'routes'} || []} ) );
        # a collection can just be a list of tables
        my @content = ( ref( $collection ) eq 'ARRAY' ) ? map { { 'type' => 'table', %{$_} }; } @{$collection} : @{$collection->{'content'} || []};
        push( @ordered, { 'level' => ($SUB_TOPICS{$topic} || 1), 'topic' => $name, 'content' => \@content } );

        my $groups = ( ref( $collection ) eq 'HASH' ) ? $collection->{'route_types'} : undef;
        next    unless ( $groups );
        my @types  = ( $topic eq 'lines_without_ref' ) ? sort( keys( %{$groups} ) ) : route_type_order( keys( %{$groups} ) );
        foreach my $route_type ( @types ) {
            push( @ordered, { 'level' => 2, 'text' => route_type_title( $route_type ), 'content' => $groups->{$route_type} } );
        }
    }

    foreach my $section ( @ordered ) {
        $section->{'text'} //= topic_title( $section->{'topic'} );
        if ( $section->{'text'} ) {
            my $level = $section->{'level'};
            $counters[$level]++;
            $counters[$_] = 0    foreach ( $level+1 .. 6 );
            $section->{'number'} = join( '.', @counters[1 .. $level] );
            $section->{'id'}     = topic_anchor( $section->{'topic'} ) // 'A' . $section->{'number'};
        }
        $section->{'nav'} = local_navigation( $section->{'content'} );
    }

    return @ordered;
}


# the known route types come first, in a fixed order
sub route_type_order {
    my %wanted = map { $_ => 1; } @_;
    my @known  = grep { delete( $wanted{$_} ); } @ROUTE_TYPES;
    return ( @known, sort( keys( %wanted ) ) );
}


sub route_type_title {
    my $route_type = shift;
    my %names      = ( 'bus'        => gettext('Bus'),
                       'coach'      => gettext('Coach'),
                       'share_taxi' => gettext('Share-Taxi'),
                       'train'      => gettext('Train/Suburban-Train'),
                       'tram'       => gettext('Tram/Streetcar'),
                       'subway'     => gettext('Subway/Underground'),
                       'light_rail' => gettext('Light-Rail'),
                       'trolleybus' => gettext('Trolley Bus'),
                       'ferry'      => gettext('Ferry'),
                       'monorail'   => gettext('Mono-Rail'),
                       'aerialway'  => gettext('Aerialway'),
                       'funicular'  => gettext('Funicular')
                     );

    return sprintf( '%s (%s)', ($names{$route_type} || $route_type), $route_type );
}


# the anchors of the sections of a topic (the others are 'A' followed by their number)
sub topic_anchor {
    my $topic = shift // return undef;

    return 'otherslines'        if ( $topic eq 'lines' );
    return 'otherlines'         if ( $topic eq 'other_lines' );
    return 'withoutref'         if ( $topic eq 'lines_without_ref' );
    return 'life-cycle-prefix'  if ( $topic eq 'life_cycle_prefix' );
    return $topic;
}


# the titles of the sections which are always the same
sub topic_title {
    my $topic = shift // '';

    return gettext("Date of Data")                                       if ( $topic eq 'dates' );
    return gettext("Hints")                                              if ( $topic eq 'hints' );
    return gettext("Not clearly assigned routes")                        if ( $topic eq 'unassigned' );
    return gettext("Other Public Transport Lines")                       if ( $topic eq 'other_lines' );
    return gettext("Public Transport Lines")                             if ( $topic eq 'lines' );
    return gettext("Public Transport Lines without 'ref'")               if ( $topic eq 'lines_without_ref' );
    return gettext("Routes with life-cycle prefix")                      if ( $topic eq 'life_cycle_prefix' );
    return gettext("Excluded relations - excluded by 'key-value' pair")  if ( $topic eq 'excluded' );
    return gettext("More Relations")                                     if ( $topic eq 'morerelations' );
    return gettext("Details for 'network'-Values")                       if ( $topic eq 'networkdetails' );
    return gettext("Details for 'operator'-Values")                      if ( $topic eq 'operatordetails' );
    return gettext("References to GTFS feeds and releases")              if ( $topic eq 'gtfsreferences' );
    return gettext("Conditional access statements found on ways")        if ( $topic eq 'conditional_on_ways' );
    return gettext("Considered 'network'-Values")                        if ( $topic eq 'considerednetworks' );
    return gettext("Additionally considered 'network'-Values")           if ( $topic eq 'addednetworks' );
    return gettext("Not Considered 'network'-Values")                    if ( $topic eq 'notconsiderednetworks' );
    return gettext("References to GTFS from CSV list")                   if ( $topic eq 'gtfsreferences_csv' );
    return gettext("References to GTFS from relations")                  if ( $topic eq 'gtfsreferences_relations' );

    return undef;
}


# links to the lines of the tables of a section
sub local_navigation {
    my $content = shift || [];
    my @nav     = ();

    return []    if ( $cfg{'no_additional_navigation'} );

    foreach my $table ( grep { $_->{'type'} eq 'table'; } @{$content} ) {
        foreach my $row ( grep { $_->{'type'} eq 'subheader' && $_->{'id'}; } @{$table->{'rows'}} ) {
            my $text = PtnaOutput::Msg::jointext( ' ', @{$row->{'refs'}} );
            push( @nav, { 'id' => $row->{'id'}, 'text' => $text, 'colour' => $row->{'colour'}, 'text_colour' => $row->{'text_colour'} } )    if ( $text ne '' );
        }
    }
    return \@nav;
}


